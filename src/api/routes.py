        solar_irradiance_w_m2=float(snap.get("solar_irradiance_w_m2", 0.0)),
        electricity_price_usd_kwh=float(snap.get("electricity_price_usd_kwh", 0.0)),
        baseline_power_kw=float(snap.get("baseline_power_kw", 0.0)),
        rl_power_kw=float(snap.get("rl_power_kw", 0.0)),
        power_saved_kw=float(snap.get("power_saved_kw", 0.0)),
        instantaneous_savings_pct=float(snap.get("instantaneous_savings_pct", 0.0)),
        cumulative_baseline_energy_kwh=float(snap.get("cumulative_baseline_energy_kwh", 0.0)),
        cumulative_rl_energy_kwh=float(snap.get("cumulative_rl_energy_kwh", 0.0)),
