@router.post("/simulation/control", response_model=SimulationControlResponse)
async def simulation_control_endpoint(
    request: Request, body: SimulationControlRequest
) -> SimulationControlResponse:
    """Handles start/pause/step/reset/set_speed/set_weather_preset commands."""
    coord = _coordinator(request)
    if not coord.is_initialized():
        coord.initialize()

    import asyncio

    action = body.action
    extra: Dict[str, Any] = {}

    if action == "start":
        if body.speed is not None:
            await asyncio.to_thread(coord.set_speed, body.speed)
        await asyncio.to_thread(coord.start)
    elif action == "pause":
        await asyncio.to_thread(coord.pause)
    elif action == "reset":
        await asyncio.to_thread(coord.reset)
    elif action == "step":
        steps = int(body.steps or 1)
        latest = await asyncio.to_thread(coord.step, steps)
        if latest is not None:
            extra["step_executed"] = int(latest.step)
    elif action == "set_speed":
        if body.speed is None:
            raise HTTPException(status_code=422, detail="speed is required for set_speed")
        new_speed = await asyncio.to_thread(coord.set_speed, body.speed)
        extra["new_speed"] = float(new_speed)
    elif action == "set_weather_preset":
        if body.preset is None:
            raise HTTPException(status_code=422, detail="preset is required for set_weather_preset")
        try:
            preset_enum = WeatherPreset(body.preset)
        except ValueError as exc:
            raise HTTPException(
                status_code=422,
                detail=f"unknown preset '{body.preset}'",
            ) from exc
        # Apply preset: simplest path is to swap the underlying generator's preset.
        await asyncio.to_thread(_apply_preset, coord, preset_enum)
        extra["preset"] = preset_enum.value

    return SimulationControlResponse(
        status="success",
        action=action,
        running=coord.is_running(),
        speed=coord.get_speed(),
        extra=extra,
    )


def _apply_preset(coord: SimulationCoordinator, preset: WeatherPreset) -> None:
    """Re-initializes the runner's weather generator with a new preset."""
    runner = coord.runner
    runner.env.weather_gen.reset(preset=preset)
    runner.weather_preset = preset
    # The runner's own weather_preset is informational; the env's weather_gen drives everything.


@router.get("/status", response_model=StatusResponse)
async def status_endpoint(request: Request) -> StatusResponse:
    """Returns current system status (health, running flag, sim tick, etc.)."""
    coord = _coordinator(request)
    if not coord.is_initialized():
        coord.initialize()

    import asyncio

    sim_minutes = await asyncio.to_thread(coord.get_current_sim_time_minutes)
    return StatusResponse(
        status="healthy",
        running=coord.is_running(),
        speed=coord.get_speed(),
        initialized=coord.is_initialized(),
        subscribers=coord.get_subscriber_count(),
        sim_step=int(sim_minutes / 5.0),
        sim_time_minutes=float(sim_minutes),
        llm_engine_active=bool(getattr(coord, "_llm_engine_active", False)),
    )


@router.get("/stream")
async def stream_endpoint(request: Request) -> StreamingResponse:
    """Server-Sent Events telemetry stream."""
    coord = _coordinator(request)
    if not coord.is_initialized():
        coord.initialize()

    generator = telemetry_event_stream(coord)
    return StreamingResponse(
        generator,
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",  # disable nginx buffering
            "Content-Type": "text/event-stream",
        },
    )


