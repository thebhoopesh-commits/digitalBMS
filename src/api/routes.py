    """Returns the latest metrics snapshot plus a short history window."""
    coord = _coordinator(request)
    if not coord.is_initialized():
        coord.initialize()

    import asyncio

    snap = await asyncio.to_thread(coord.get_metrics_snapshot)
    history_models = await asyncio.to_thread(coord.get_telemetry_history, limit)
